#!/usr/bin/env bash
# Download the raw public MS/MS libraries into data/raw/<dataset>/.
#
# Usage: bash data_scripts/public/download_public_datasets.sh [msnlib] [massbank] [nplib1]   (default: all)
#
#   msnlib    MSnLib, Brungs et al., Nat. Methods 2025. Zenodo concept record 11163380;
#             MS2-only positive-mode .mgf files from version record $MSNLIB_RECORD.
#   massbank  MassBank EU, NIST-format .msp from GitHub release $MASSBANK_RELEASE.
#   nplib1    canopus_train_public (NPLIB1, GNPS subset) from the ms-pred Zenodo record 8433354.
#
# Pin the versions below for reproducibility; check the source pages for newer releases.
set -euo pipefail

MSNLIB_RECORD=${MSNLIB_RECORD:-21105617}      # 2026-07-01 version, 9 compound libraries
MASSBANK_RELEASE=${MASSBANK_RELEASE:-2026.11}
NPLIB1_URL=${NPLIB1_URL:-https://zenodo.org/records/8433354/files/canopus_train_public.zip?download=1}
raw_dir=${raw_dir:-data/raw}

datasets=("$@")
[ ${#datasets[@]} -eq 0 ] && datasets=(msnlib massbank nplib1)

fetch() {  # fetch <url> <out>: skip files that are already complete
  if [ -s "$2" ]; then echo "Found $2"; return; fi
  echo "Downloading $1"
  curl -fsSL --retry 4 -o "$2.part" "$1"
  mv "$2.part" "$2"
}

for dataset in "${datasets[@]}"; do
  out=$raw_dir/$dataset
  mkdir -p "$out"
  case $dataset in
    msnlib)
      curl -fsSL "https://zenodo.org/api/records/$MSNLIB_RECORD" -o "$out/record.json"
      python3 -c 'import json, sys
for f in json.load(open(sys.argv[1]))["files"]:
    if f["key"].endswith("_pos_ms2.mgf"):
        print(f["key"])' "$out/record.json" | while read -r name; do
        fetch "https://zenodo.org/records/$MSNLIB_RECORD/files/$name?download=1" "$out/$name"
      done
      ;;
    massbank)
      fetch "https://github.com/MassBank/MassBank-data/releases/download/$MASSBANK_RELEASE/MassBank_NISTformat.msp" \
        "$out/MassBank_NISTformat.msp"
      ;;
    nplib1)
      fetch "$NPLIB1_URL" "$out/canopus_train_public.zip"
      if [ ! -d "$out/canopus_train_public/spec_files" ]; then
        # Old magma/subformula outputs are in a legacy format and are regenerated by run_magma.sh.
        unzip -q -o "$out/canopus_train_public.zip" -d "$out" \
          'canopus_train_public/labels.tsv' 'canopus_train_public/splits/*' \
          'canopus_train_public/spec_files/*' 'canopus_train_public/retrieval/cands_df_split_*_50.tsv'
      fi
      ;;
    *)
      echo "Unknown dataset $dataset (expected msnlib, massbank or nplib1)"; exit 1 ;;
  esac
done
